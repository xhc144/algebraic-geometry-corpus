#!/usr/bin/env python3
"""Generate the single-file reader from the same native Chinese project.

Only local literal input commands are expanded. The two inherited custom
class/package files are embedded verbatim for extraction by TeX; all other
dependencies are ordinary installed TeX packages and the documented fonts.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'SGA4-b-zh-CN.tex'
inputs = {}

def read(path):
    data = path.read_bytes()
    inputs[str(path.relative_to(ROOT))] = hashlib.sha256(data).hexdigest()
    return data.decode('utf-8')

def expand(path, stack=()):
    if path in stack:
        raise ValueError(f'Recursive input: {path}')
    text = read(path)
    def sub(match):
        # Match only an uncommented literal input occupying its own line.
        name = match.group(1)
        target = (ROOT / name).resolve()
        if not target.is_relative_to(ROOT) or not target.is_file():
            raise ValueError(f'Nonlocal or missing input: {name}')
        return f'% BEGIN native input: {name}\n' + expand(target, stack + (path,)) + f'\n% END native input: {name}'
    return re.sub(r'(?m)^\\input\{([^}]+)\}\s*$', sub, text)

embedded = []
for original, name in [('style/amsbook.cls', 'SGA4-native-amsbook.cls'),
                       ('style/smfthm.sty', 'SGA4-native-smfthm.sty')]:
    embedded.append('\\begin{filecontents*}[overwrite]{' + name + '}\n' + read(ROOT / original) + '\n\\end{filecontents*}\n')
body = expand(ROOT / 'main.tex')
body = body.replace('{style/amsbook}', '{SGA4-native-amsbook}')
body = body.replace('{style/smfthm}', '{SGA4-native-smfthm}')
OUTPUT.write_text('% !TeX program = xelatex\n% Generated by tools/flatten.py; edit the native project and regenerate.\n' + ''.join(embedded) + body)
report = {'output': OUTPUT.name, 'sha256': hashlib.sha256(OUTPUT.read_bytes()).hexdigest(),
          'input_sha256': dict(sorted(inputs.items())),
          'method': 'Literal local inputs expanded; original custom class and theorem package embedded verbatim in filecontents*. No chapter text rewritten.',
          'external_dependencies': 'Installed TeX packages and fonts listed in BUILD.md.'}
(ROOT / 'evidence/FLATTENED_SOURCE.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
print(f'Generated {OUTPUT.name} from {len(inputs)} native input files.')
