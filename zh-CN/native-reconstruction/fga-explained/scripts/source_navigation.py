#!/usr/bin/env python3
"""Install reviewed source anchors; generate and audit original-page navigation."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

import fitz

ROOT = Path(__file__).resolve().parents[1]
CANONICAL = re.compile(r'^% SOURCE-PAGE-ANCHOR:\s*(\d+)\s*$', re.M)
PAGE_TAIL = re.compile(r',\s*(\d+(?:,\s*\d+)*)\s*$')


def prepare():
    coverage = json.loads((ROOT / 'evidence/source-coverage.json').read_text())
    blanks = set(coverage['blank_pdf_pages'])
    records = []
    for path in sorted(ROOT.rglob('*.tex')):
        if 'build' in path.relative_to(ROOT).parts:
            continue
        text = path.read_text()
        for match in CANONICAL.finditer(text):
            page = int(match[1])
            records.append({'source_pdf_page': page,
                            'file': str(path.relative_to(ROOT)),
                            'canonical_comment_line': text[:match.start()].count('\n') + 1})
        text = CANONICAL.sub(lambda m: m[0] + '\n\\sourcepage{' + m[1] + '}'
                            if not re.match(r'\s*\\sourcepage\{' + m[1] + r'\}',
                                            text[m.end():]) else m[0], text)
        if text != path.read_text():
            path.write_text(text)
    counts = Counter(row['source_pdf_page'] for row in records)
    duplicate = [n for n, count in counts.items() if count != 1]
    required = set(range(13, 352)) - blanks
    missing = sorted(required - set(counts))
    if duplicate or missing:
        raise RuntimeError(f'Duplicate anchors {duplicate}; missing body source pages {missing}')
    index = ROOT / 'backmatter/index.tex'
    text = index.read_text()
    source_text = re.sub(r'\\sourceindex\{(\d+)\}', r'\1', text)
    before = []
    output = []
    for line in source_text.splitlines():
        if re.match(r'\\(?:item|subitem|subsubitem)\b', line):
            match = PAGE_TAIL.search(line)
            if match:
                numbers = re.findall(r'\d+', match[1])
                before.extend(map(int, numbers))
                line = (line[:match.start(1)] +
                        re.sub(r'\d+', lambda m: '\\sourceindex{' + m[0] + '}', match[1]) +
                        line[match.end(1):])
        output.append(line)
    linked = '\n'.join(output) + '\n'
    assert re.sub(r'\\sourceindex\{(\d+)\}', r'\1', linked) == source_text
    index.write_text(linked)
    available = sorted(n for n in required if n in counts)
    rows = []
    for original in range(1, 340):
        pdf = original + 12
        previous = max((n for n in available if n < pdf), default=available[0])
        following = min((n for n in available if n > pdf), default=available[-1])
        rows.append({'original_printed_page': original, 'source_pdf_page': pdf,
                     'source_blank': pdf in blanks,
                     'previous_source_anchor': previous, 'next_source_anchor': following})
    out = [
        '% Editorial source-page map, generated by scripts/source_navigation.py.',
        r'\chapter*{原书页码对照}',
        r'\phantomsection\addcontentsline{toc}{chapter}{原书页码对照}',
        r'\markboth{原书页码对照}{原书页码对照}',
        '本表为中文重建本新增的检索工具。原索引的全部条目与原书页码均保留；点击索引页码可转到本表，点击本表的中译印页区间可回正文。',
        '原书印页加12即为底本PDF页。中译检索区间以前后相邻非空白源页的锚点为界，并各向外放宽一中译页。跨页段落和公式不强行切断，因此区间有重叠；区间不表示逐字分页一一对应。星号标记原书空白页。',
        r'\begingroup\small\setlength{\tabcolsep}{9pt}',
        r'\begin{longtable}{rcc}',
        r'\toprule 原书印页（底本PDF）&中译印页检索区间&中译PDF页区间\\\midrule\endfirsthead',
        r'\toprule 原书印页（底本PDF）&中译印页检索区间&中译PDF页区间\\\midrule\endhead',
        r'\bottomrule\endfoot',
    ]
    out += [r'\sourcemaprow' + ''.join('{' + str(value) + '}' for value in [
        row['original_printed_page'], row['source_pdf_page'],
        row['previous_source_anchor'], row['next_source_anchor']]) +
        ('{*}' if row['source_blank'] else '{}') for row in rows]
    out += [r'\end{longtable}', r'\endgroup', r'\clearpage']
    (ROOT / 'backmatter/source-page-map.tex').write_text('\n'.join(out) + '\n')
    plan = {'source_sha256': coverage['source_sha256'], 'anchors': records,
            'required_nonblank_body_anchors': len(required), 'missing_anchors': missing,
            'duplicate_anchors': duplicate, 'index_page_references_preserved': before,
            'index_page_reference_count': len(before), 'index_unique_original_pages': len(set(before)),
            'map_rows': rows,
            'mapping_policy': 'Conservative interval between adjacent reviewed source anchors, expanded by one translated page on each side; no exact line/page equivalence claimed.'}
    (ROOT / 'evidence/source-navigation-plan.json').write_text(json.dumps(plan, ensure_ascii=False, indent=2) + '\n')
    print(f'Installed {len(records)} canonical anchors, linked {len(before)} unchanged index references; 339 map rows.')


def audit():
    plan = json.loads((ROOT / 'evidence/source-navigation-plan.json').read_text())
    aux = (ROOT / 'build/FGA-explained-zh-CN.aux').read_text()
    native = {int(n): int(page) for n, page in re.findall(
        r'\\newlabel\{origpdf:(\d+)\}\{\{[^}]*\}\{(\d+)\}', aux)}
    absolute = {int(n): int(page) for n, page in re.findall(
        r'\\zref@newlabel\{origabs:(\d+)\}\{[^\n]*?\\abspage\{(\d+)\}', aux)}
    pdfpath = ROOT / 'FGA-explained-zh-CN.pdf'
    doc = fitz.open(pdfpath)
    mapping = []
    for row in plan['map_rows']:
        a, b = row['previous_source_anchor'], row['next_source_anchor']
        assert a in native and b in native and a in absolute and b in absolute, row
        lo, hi = max(1, absolute[a] - 1), absolute[b] + 1
        assert 1 <= lo <= hi <= len(doc), row
        mapping.append({**row, 'chinese_printed_range': [max(1, native[a] - 1), native[b] + 1],
                        'chinese_pdf_range': [lo, hi]})
    anchors = [r['source_pdf_page'] for r in plan['anchors']]
    missing_abs = sorted(set(anchors) - set(absolute))
    assert not missing_abs, missing_abs
    source_order = sorted(n for n in absolute if 13 <= n <= 351)
    nonmonotone = [(a, b) for a, b in zip(source_order, source_order[1:]) if absolute[a] > absolute[b]]
    assert not nonmonotone, nonmonotone
    mapped_pages = {r['original_printed_page'] for r in mapping}
    assert set(plan['index_page_references_preserved']) <= mapped_pages
    report = {'pdf_sha256': hashlib.sha256(pdfpath.read_bytes()).hexdigest(),
              'pdf_pages': len(doc), 'source_anchors': len(anchors),
              'required_nonblank_body_anchors': plan['required_nonblank_body_anchors'],
              'missing_absolute_anchors': missing_abs, 'nonmonotone_body_anchors': nonmonotone,
              'original_index_page_reference_count': plan['index_page_reference_count'],
              'original_index_unique_pages': plan['index_unique_original_pages'],
              'original_index_references_all_mapped': True, 'mapping': mapping,
              'policy': plan['mapping_policy']}
    (ROOT / 'evidence/source-page-map.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(f'Navigation verified: {len(anchors)} anchors; 339 original pages; all {plan["index_page_reference_count"]} index references mapped.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'audit'])
    args = parser.parse_args()
    {'prepare': prepare, 'audit': audit}[args.action]()
